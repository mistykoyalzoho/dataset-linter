//! OpenAI-powered semantic analysis for dataset quality.
//!
//! Uses GPT models to provide natural-language insights about
//! dataset issues that statistical rules alone can't catch:
//! - Column purpose inference
//! - Semantic type suggestions
//! - Fix recommendations in natural language
//! - Dataset summary generation

use async_openai::config::OpenAIConfig as OAIConfig;
use async_openai::types::{
    ChatCompletionRequestMessage, ChatCompletionRequestSystemMessage,
    ChatCompletionRequestUserMessage, CreateChatCompletionRequestArgs,
};
use async_openai::Client;
use dataset_linter_core::{Dataset, LintResult, Severity};
use serde::{Deserialize, Serialize};

/// Configuration for the OpenAI analyzer.
#[derive(Debug, Clone)]
pub struct OpenAIConfig {
    pub model: String,
    pub max_tokens: u16,
    pub temperature: f32,
}

impl Default for OpenAIConfig {
    fn default() -> Self {
        Self {
            model: "gpt-4o-mini".into(),
            max_tokens: 2048,
            temperature: 0.3,
        }
    }
}

/// A semantic insight generated by the AI.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AIInsight {
    pub column: Option<String>,
    pub category: InsightCategory,
    pub summary: String,
    pub recommendation: String,
    pub confidence: f32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum InsightCategory {
    TypeSuggestion,
    QualityIssue,
    FeatureEngineering,
    DataLeakage,
    BiasSignal,
    General,
}

/// The AI-powered dataset analyzer.
pub struct Analyzer {
    client: Client<OAIConfig>,
    config: OpenAIConfig,
}

impl Analyzer {
    pub fn new(config: OpenAIConfig) -> Self {
        Self {
            client: Client::new(),
            config,
        }
    }

    /// Analyze a dataset and its lint results, returning AI-generated insights.
    pub async fn analyze(
        &self,
        dataset: &Dataset,
        lint_result: &LintResult,
    ) -> anyhow::Result<Vec<AIInsight>> {
        let dataset_summary = self.build_dataset_summary(dataset);
        let lint_summary = self.build_lint_summary(lint_result);

        let prompt = format!(
            r#"You are a senior ML engineer reviewing a dataset for quality issues.

## Dataset Summary
{dataset_summary}

## Automated Lint Results
{lint_summary}

Based on this information, provide insights in JSON format. For each insight:
- "column": column name or null for dataset-level
- "category": one of "type_suggestion", "quality_issue", "feature_engineering", "data_leakage", "bias_signal", "general"
- "summary": one-sentence insight
- "recommendation": actionable fix
- "confidence": 0.0-1.0

Return a JSON array of insights. Focus on non-obvious issues the automated rules missed.
Limit to 5 most important insights."#
        );

        let request = CreateChatCompletionRequestArgs::default()
            .model(&self.config.model)
            .max_tokens(self.config.max_tokens as u32)
            .temperature(self.config.temperature)
            .messages([
                ChatCompletionRequestMessage::System(ChatCompletionRequestSystemMessage {
                    content: "You are a dataset quality expert. Respond only with valid JSON."
                        .into(),
                    name: None,
                }),
                ChatCompletionRequestMessage::User(ChatCompletionRequestUserMessage {
                    content: prompt.into(),
                    name: None,
                }),
            ])
            .build()?;

        let response = self.client.chat().create(request).await?;

        let content = response
            .choices
            .first()
            .and_then(|c| c.message.content.clone())
            .unwrap_or_default();

        // Parse the JSON array of insights
        let insights: Vec<AIInsight> = serde_json::from_str(&content).unwrap_or_else(|_| {
            // Fallback: wrap the raw response as a single insight
            vec![AIInsight {
                column: None,
                category: InsightCategory::General,
                summary: content,
                recommendation: "Review the AI analysis above.".into(),
                confidence: 0.5,
            }]
        });

        Ok(insights)
    }

    /// Generate a natural-language summary of the dataset.
    pub async fn summarize(&self, dataset: &Dataset) -> anyhow::Result<String> {
        let summary = self.build_dataset_summary(dataset);

        let request = CreateChatCompletionRequestArgs::default()
            .model(&self.config.model)
            .max_tokens(512u32)
            .temperature(0.5)
            .messages([
                ChatCompletionRequestMessage::System(
                    ChatCompletionRequestSystemMessage {
                        content: "You are a data scientist. Write concise, technical summaries.".into(),
                        name: None,
                    },
                ),
                ChatCompletionRequestMessage::User(
                    ChatCompletionRequestUserMessage {
                        content: format!(
                            "Write a 2-3 sentence summary of this dataset for an ML practitioner:\n\n{summary}"
                        ).into(),
                        name: None,
                    },
                ),
            ])
            .build()?;

        let response = self.client.chat().create(request).await?;
        Ok(response
            .choices
            .first()
            .and_then(|c| c.message.content.clone())
            .unwrap_or_else(|| "No summary generated.".into()))
    }

    fn build_dataset_summary(&self, dataset: &Dataset) -> String {
        let mut lines = vec![
            format!("Name: {}", dataset.name),
            format!("Rows: {}, Columns: {}", dataset.nrows(), dataset.ncols()),
            String::new(),
            "Columns:".into(),
        ];

        for col in &dataset.columns {
            let mut line = format!("  - {} ({})", col.name, col.dtype);
            if col.null_pct > 0.0 {
                line += &format!(", {:.1}% null", col.null_pct);
            }
            line += &format!(", {} unique", col.unique_count);
            lines.push(line);
        }

        lines.join("\n")
    }

    fn build_lint_summary(&self, result: &LintResult) -> String {
        let mut lines = vec![format!(
            "{} errors, {} warnings, {} info",
            result.error_count(),
            result.warning_count(),
            result.info_count()
        )];

        for diag in &result.diagnostics {
            if diag.severity >= Severity::Warning {
                lines.push(format!(
                    "[{}] {}: {}",
                    diag.severity, diag.code, diag.message
                ));
            }
        }

        lines.join("\n")
    }
}
